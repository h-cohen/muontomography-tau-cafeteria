"""results/*.json -> LaTeX macros: the paper never contains a typed number.

A value with a sibling `<key>_sigma` is rounded to the decimal place of that
sigma's second significant digit, and the sigma with it; any other float keeps
three significant digits; integers are verbatim; NaN renders as a dash, magnitudes below 1e-3 go
through siunitx `\\num`, negatives are wrapped in `\\ensuremath`; infinities raise.
"""

import json
import math
import re
from pathlib import Path

_DIGITS = "Zero One Two Three Four Five Six Seven Eight Nine".split()


def macro_name(stem: str, key: str) -> str:
    parts = re.split(r"[_\-.]", f"{stem}_{key}")
    name = "".join(p[:1].upper() + p[1:] for p in parts if p)
    return re.sub(r"\d", lambda m: _DIGITS[int(m.group())], name)


def _decimals(sigma: float) -> int:
    return max(0, 1 - int(math.floor(math.log10(abs(sigma)))))


def _plain(value: float, sigma: float | None) -> str:
    if sigma is not None and math.isfinite(sigma) and sigma > 0:
        return f"{value:.{_decimals(sigma)}f}"
    if abs(value) >= 100:
        return f"{value:.0f}"
    if value != 0 and abs(value) < 1e-3:
        return f"\\num{{{value:.3g}}}"
    return f"{value:.3g}"


def format_value(value: float | int, sigma: float | None = None) -> str:
    if isinstance(value, int):
        return str(value)
    if math.isnan(value):
        return "--"
    text = _plain(value, sigma)
    return f"\\ensuremath{{{text}}}" if text.startswith("-") else text


def flatten(results_dir: Path) -> dict[str, str]:
    macros: dict[str, str] = {}
    origin: dict[str, str] = {}
    for path in sorted(Path(results_dir).glob("*.json")):
        doc = json.loads(path.read_text())
        scalars = {
            k: v for k, v in doc.items() if isinstance(v, int | float) and not isinstance(v, bool)
        }
        for key, value in scalars.items():
            if isinstance(value, float) and math.isinf(value):
                raise ValueError(f"non-finite value in {path.name}:{key}")
            if key.endswith("_sigma") and key[: -len("_sigma")] in scalars:
                base = scalars[key[: -len("_sigma")]]
                text = (
                    format_value(value, value) if isinstance(base, float) else format_value(value)
                )
            else:
                text = format_value(value, scalars.get(f"{key}_sigma"))
            name = macro_name(path.stem, key)
            if name in macros:
                raise ValueError(
                    f"macro \\{name} from {path.name}:{key} collides with {origin[name]}"
                )
            macros[name] = text
            origin[name] = f"{path.name}:{key}"
    return macros


def write_numbers(results_dir: Path, out_path: Path) -> Path:
    lines = ["% Generated by `cafetomo numbers` from results/*.json. Do not edit."]
    lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in sorted(flatten(results_dir).items())]
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(lines) + "\n")
    return out_path


CONFIG_SECTIONS = (
    "detector",
    "binning",
    "opacity",
    "volume",
    "reconstruction",
    "selfcal",
    "autofocus",
    "beams",
    "beamdepth",
    "uncertainty",
)


def _flat_numbers(value) -> list:
    if isinstance(value, list | tuple):
        return [x for v in value for x in _flat_numbers(v)]
    return [value]


def _is_number(v) -> bool:
    return isinstance(v, int | float) and not isinstance(v, bool)


def config_macros(raw: dict) -> dict[str, str]:
    """Analysis settings as `\\Config<Section><Key>` macros; list items get index words."""
    out: dict[str, str] = {}
    for section in CONFIG_SECTIONS:
        for key, value in (raw.get(section) or {}).items():
            if _is_number(value):
                out[macro_name(f"config_{section}", key)] = format_value(value)
            elif isinstance(value, list | tuple):
                items = _flat_numbers(value)
                if items and all(_is_number(v) for v in items):
                    for i, v in enumerate(items):
                        out[macro_name(f"config_{section}", f"{key}_{i}")] = format_value(v)
    return out


def paper_constants() -> dict[str, str]:
    """Fixed algorithm constants the paper quotes, read from the modules that use them."""
    from cafetomo import arraydepth, beamdepth, beams, inversion, raycast, selfcal

    values = {
        "samples_per_voxel": raycast.SAMPLES_PER_VOXEL,
        "tv_scale_percentile": inversion.TV_SCALE_PERCENTILE,
        "prox_inner_iterations": inversion.PROX_INNER_ITERATIONS,
        "powell_max_iter": selfcal.POWELL_MAX_ITER,
        "fft_window_tan": beams.FFT_WINDOW_TAN,
        "fft_min_bins": beams.FFT_MIN_BINS,
        "fft_min_harmonic": beams.FFT_MIN_HARMONIC,
        "gate_y_band_m": beams.GATE_Y_BAND_M,
        "gate_smooth_m": beams.GATE_SMOOTH_M,
        "continued_per_end": arraydepth.CONTINUED_PER_END,
        "column_max": arraydepth.COLUMN_MAX,
        "column_start": arraydepth.COLUMN_START,
        "shift_max_m": arraydepth.SHIFT_MAX_M,
        "at_bound_fraction": beamdepth.AT_BOUND_FRACTION,
    }
    out = {macro_name("const", k): format_value(v) for k, v in values.items()}
    for i, v in enumerate(arraydepth.ARRAY_H_STARTS_M):
        out[macro_name("const", f"array_h_starts_m_{i}")] = format_value(v)
    return out


def archive_macros(volume_npz: Path) -> dict[str, str]:
    """Scalars kept only in the reviewed baseline volume (not in results/)."""
    import numpy as np

    with np.load(volume_npz) as d:
        info = json.loads(str(d["meta"]))["info"]
    return {
        "ArchiveBestIter": format_value(int(info["best_iter"])),
        "ArchiveNIterUsed": format_value(int(info["n_iter_used"])),
        "ArchiveChisqStart": format_value(float(info["chi2_history"][0])),
    }


def write_config_numbers(config: Path, volume_npz: Path, out: Path) -> Path:
    import yaml

    macros = {
        **config_macros(yaml.safe_load(Path(config).read_text())),
        **paper_constants(),
        **archive_macros(Path(volume_npz)),
    }
    lines = ["% Generated by `cafetomo config-numbers` from the config, code constants"]
    lines.append("% and the baseline volume. Do not edit.")
    lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in sorted(macros.items())]
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n")
    return out


def raw_macros(rawdata: Path, cfg) -> dict[str, str]:
    """Preliminary raw-chain macros: rawdata.json scalars and the calibration and 2D-view
    settings, as `\\Raw...`. Not reviewed into results/; the text marks them preliminary."""
    import dataclasses

    out: dict[str, str] = {}
    for key, value in json.loads(Path(rawdata).read_text()).items():
        if _is_number(value):
            out[macro_name("raw", key)] = format_value(value)
    for section in ("calibration", "view"):
        settings = getattr(cfg, section)
        for f in dataclasses.fields(settings):
            value = getattr(settings, f.name)
            if _is_number(value):
                out[macro_name(f"raw_{section}", f.name)] = format_value(value)
    return out


def write_raw_numbers(rawdata: Path, config: Path, out: Path) -> Path:
    from cafetomo.config import load_config

    macros = raw_macros(rawdata, load_config(config))
    lines = ["% Generated by `cafetomo raw-numbers`: PRELIMINARY raw-chain values, not reviewed."]
    lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in sorted(macros.items())]
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n")
    return out
